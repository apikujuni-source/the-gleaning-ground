import { getDatabase } from '@netlify/database';

export const NAME_MAX = 80;
export const BODY_MAX = 2000;
export const TITLE_MAX = 200;

export function db() {
  return getDatabase();
}

// Strip control characters (keeping line breaks in comment bodies) and trim.
export function clean(value, max, { multiline = false } = {}) {
  const pattern = multiline ? /[\u0000-\u0009\u000b-\u001f\u007f]/g : /[\u0000-\u001f\u007f]/g;
  let text = String(value ?? '').replace(/\r\n?/g, '\n').replace(pattern, ' ').trim();
  if (multiline) text = text.replace(/\n{3,}/g, '\n\n');
  return text.slice(0, max);
}

// Post URLs are generated by Eleventy, e.g. /devotionals/2025-11-25-justified-by-faith/
export function normalizePostPath(value) {
  const path = String(value || '').trim().toLowerCase();
  return /^\/[a-z0-9-]+\/[a-z0-9][a-z0-9-]{0,160}\/$/.test(path) ? path : '';
}

export function toPublic(row) {
  return {
    id: row.id,
    name: row.author_name,
    body: row.body,
    createdAt: new Date(row.created_at).toISOString()
  };
}
